import * as path from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "bun:test";
import { getAgentDir } from "@oh-my-pi/pi-utils";
import { getProxyForProvider, setLlmTunnelProxy, wrapFetchForProxy, __resetProxyCache } from "@oh-my-pi/pi-ai";
import { buildNonInteractiveEnv } from "../src/exec/non-interactive-env";
import { BUILTIN_TUNNEL_SLASH_COMMANDS } from "../src/slash-commands/builtin-tunnel";
import { setTunnelManagerForTest, stopTunnel } from "../src/tunnel/coordinator";
import { UpstreamManager } from "../src/tunnel/manager";
import { fetchSubscriptionUpstreams, parseSubscriptionContent } from "../src/tunnel/parser";
import type { LlmTunnelConfig, VlessUpstreamConfig } from "../src/tunnel/types";

describe("tunnel split-networking & mock tests", () => {
	let savedTunnelYaml: string | null = null;
	const tunnelYamlPath = path.join(path.dirname(getAgentDir()), "tunnel.yaml");

	beforeAll(async () => {
		try {
			if (await Bun.file(tunnelYamlPath).exists()) {
				savedTunnelYaml = await Bun.file(tunnelYamlPath).text();
			}
		} catch {
			// Ignore
		}
	});

	afterAll(async () => {
		try {
			if (savedTunnelYaml !== null) {
				await Bun.write(tunnelYamlPath, savedTunnelYaml);
			} else {
				await Bun.write(
					tunnelYamlPath,
					'# Generated by vomp /vpn TUI\nllm_tunnel:\n  enabled: true\n  strategy: "failover"\n  upstreams: []\n',
				);
			}
		} catch {
			// Ignore
		}
	});

	const sampleVless1 =
		"vless://11111111-1111-1111-1111-111111111111@node1.vpn.com:443?security=reality&sni=sni1.com&pbk=ib1kz6BCdMgxv9fqC8rKvrrKrHYDOc0gK3YUcY4eABU&sid=0123456789abcdef&type=grpc&serviceName=grpc1#node-us";
	const sampleVless2 =
		"vless://22222222-2222-2222-2222-222222222222@node2.vpn.com:443?security=reality&sni=sni2.com&pbk=ib1kz6BCdMgxv9fqC8rKvrrKrHYDOc0gK3YUcY4eABU&sid=0123456789abcdef&type=tcp#node-eu";
	const sampleHy2 = "hy2://secretpass@node3.vpn.com:8443?sni=sni3.com&insecure=1#node-sg";

	it("parses plaintext subscription with multiple connections", () => {
		const rawContent = [sampleVless1, sampleVless2, sampleHy2].join("\n");
		const upstreams = parseSubscriptionContent(rawContent);

		expect(upstreams).toHaveLength(3);
		expect(upstreams[0]?.name).toBe("node-us");
		expect(upstreams[0]?.type).toBe("vless");
		expect((upstreams[0] as VlessUpstreamConfig).server).toBe("node1.vpn.com");
		expect((upstreams[0] as VlessUpstreamConfig).network).toBe("grpc");

		expect(upstreams[1]?.name).toBe("node-eu");
		expect((upstreams[1] as VlessUpstreamConfig).server).toBe("node2.vpn.com");

		expect(upstreams[2]?.name).toBe("node-sg");
		expect(upstreams[2]?.type).toBe("hysteria2");
	});

	it("parses base64-encoded subscription with multiple connections", () => {
		const rawContent = [sampleVless1, sampleVless2].join("\n");
		const base64Content = Buffer.from(rawContent).toString("base64");
		const upstreams = parseSubscriptionContent(base64Content);

		expect(upstreams).toHaveLength(2);
		expect(upstreams[0]?.name).toBe("node-us");
		expect(upstreams[1]?.name).toBe("node-eu");
	});

	it("fetches subscription via mock fetch and updates manager pool", async () => {
		const rawContent = [sampleVless1, sampleVless2, sampleHy2].join("\n");
		const mockFetch = async () =>
			new Response(Buffer.from(rawContent).toString("base64"), { status: 200, statusText: "OK" });

		const nodes = await fetchSubscriptionUpstreams(
			"https://provider.example.com/sub",
			mockFetch as unknown as typeof fetch,
		);
		expect(nodes).toHaveLength(3);

		const config: LlmTunnelConfig = { enabled: true, upstreams: nodes };
		const manager = new UpstreamManager(config);

		expect(manager.activeUpstream?.name).toBe("node-us");
		await manager.switchUpstream("node-eu");
		expect(manager.activeUpstream?.name).toBe("node-eu");

		// Add new subscription dynamically
		const extraVless = "vless://33333333-3333-3333-3333-333333333333@node4.vpn.com:443#node-jp";
		manager.loadSubscription(extraVless);
		expect(manager.upstreams).toHaveLength(4);
		await manager.switchUpstream("node-jp");
		expect(manager.activeUpstream?.name).toBe("node-jp");
	});

	it("routes internal LLM traffic through proxy while bypassing host network", async () => {
		const proxyUrl = "http://127.0.0.1:20807";
		setLlmTunnelProxy(proxyUrl);

		try {
			// 1. LLM requests route through tunnel proxy
			expect(getProxyForProvider("anthropic")).toBe(proxyUrl);
			expect(getProxyForProvider("openai")).toBe(proxyUrl);

			let proxiedInit: RequestInit | undefined;
			const mockFetch = async (_url: string | URL | Request, init?: RequestInit) => {
				proxiedInit = init;
				return new Response("ok", { status: 200 });
			};

			const wrapped = wrapFetchForProxy(mockFetch, "anthropic");
			await wrapped("https://api.anthropic.com/v1/messages", {});
			expect((proxiedInit as Record<string, unknown>)?.proxy).toBe(proxyUrl);

			// 2. Direct / localhost requests bypass the proxy
			let localhostInit: RequestInit | undefined;
			const localhostFetch = async (_url: string | URL | Request, init?: RequestInit) => {
				localhostInit = init;
				return new Response("ok", { status: 200 });
			};
			const wrappedLocal = wrapFetchForProxy(localhostFetch, "anthropic");
			await wrappedLocal("http://127.0.0.1:3000/internal", {});
			expect((localhostInit as Record<string, unknown>)?.proxy).toBeUndefined();

			// 3. Host network environment (bash child processes) is cleansed of all proxy variables
			const childEnv = buildNonInteractiveEnv({
				HTTP_PROXY: "http://127.0.0.1:20807",
				HTTPS_PROXY: "http://127.0.0.1:20807",
				ALL_PROXY: "socks5://127.0.0.1:20807",
				CUSTOM_TOOL_VAR: "allowed",
			});

			expect(childEnv.CUSTOM_TOOL_VAR).toBe("allowed");
			expect(childEnv).not.toHaveProperty("HTTP_PROXY");
			expect(childEnv).not.toHaveProperty("HTTPS_PROXY");
			expect(childEnv).not.toHaveProperty("ALL_PROXY");

			// 4. Global fetch calls to Cloud Code Assist / Gemini route through active tunnel proxy
			__resetProxyCache();
			const original = globalThis.fetch;
			try {
				let globalCallInit: RequestInit | undefined;
				globalThis.fetch = (async (_input: string | URL | Request, init?: RequestInit) => {
					globalCallInit = init;
					return new Response("ok", { status: 200 });
				}) as typeof globalThis.fetch;
				setLlmTunnelProxy(proxyUrl);
				await globalThis.fetch("https://cloudcode-pa.googleapis.com/v1internal:streamGenerateContent?alt=sse", {
					method: "POST",
				});
				expect((globalCallInit as Record<string, unknown>)?.proxy).toBe(proxyUrl);
			} finally {
				__resetProxyCache();
				globalThis.fetch = original;
			}
		} finally {
			setLlmTunnelProxy(null);
			expect(getProxyForProvider("anthropic")).toBeUndefined();
		}
	});

	it("configures tunnel from TUI and slash command", async () => {
		const nodes = parseSubscriptionContent([sampleVless1, sampleVless2].join("\n"));
		const manager = new UpstreamManager({ enabled: true, upstreams: nodes, strategy: "failover" });
		setTunnelManagerForTest(manager);

		const cmd = BUILTIN_TUNNEL_SLASH_COMMANDS.find(c => c.name === "tunnel")!;
		let outputText = "";
		const runtime = {
			output: async (text: string) => {
				outputText = text;
			},
		};

		// 1. Status command
		await cmd.handle?.({ name: "tunnel", args: "status", text: "/tunnel status" } as never, runtime as never);
		expect(outputText).toContain("node-us");
		expect(outputText).toContain("node-eu");

		// 2. Switch node command
		await cmd.handle?.({ name: "tunnel", args: "node-eu", text: "/tunnel node-eu" } as never, runtime as never);
		expect(manager.activeUpstream?.name).toBe("node-eu");
		expect(outputText).toContain("Switched active upstream to: node-eu");

		// 3. Strategy switch command
		await cmd.handle?.(
			{ name: "tunnel", args: "strategy lowest_latency", text: "/tunnel strategy lowest_latency" } as never,
			runtime as never,
		);
		expect(manager.strategy).toBe("lowest_latency");

		// 4. Interactive TUI selector simulation
		let statusMsg = "";
		const tuiContext = {
			editor: { setText: () => {} },
			showStatus: (msg: string) => {
				statusMsg = msg;
			},
			showError: (msg: string) => {
				statusMsg = `ERR: ${msg}`;
			},
			showHookSelector: async (_title: string, options: string[]) => {
				if (options.some(o => o.startsWith("Switch Node"))) return options[0]; // pick switch node
				return "node-us"; // pick node-us
			},
		};
		await cmd.handleTui?.({ name: "tunnel", args: "", text: "/tunnel" } as never, { ctx: tuiContext } as never);
		expect(manager.activeUpstream?.name).toBe("node-us");
		expect(statusMsg).toContain("Tunnel switched to node-us");

		// 5. Interactive strategy toggle simulation
		const toggleContext = {
			editor: { setText: () => {} },
			showStatus: (msg: string) => {
				statusMsg = msg;
			},
			showHookSelector: async (_title: string, options: string[]) => options[1], // Toggle strategy
		};
		await cmd.handleTui?.({ name: "tunnel", args: "", text: "/tunnel" } as never, { ctx: toggleContext } as never);
		expect(manager.strategy).toBe("failover");
		expect(statusMsg).toContain("Strategy switched to failover");

		await stopTunnel();
		setTunnelManagerForTest(null);
	});

	it("prompts interactive setup in TUI when no upstreams configured and adds subscription directly", async () => {
		const emptyManager = new UpstreamManager({ enabled: true, upstreams: [] });
		setTunnelManagerForTest(emptyManager);
		const cmd = BUILTIN_TUNNEL_SLASH_COMMANDS.find(c => c.name === "vpn")!;

		let statusMsg = "";
		let errorMsg = "";
		const setupContext = {
			editor: { setText: () => {} },
			showStatus: (msg: string) => {
				statusMsg = msg;
			},
			showError: (msg: string) => {
				errorMsg = msg;
			},
			showHookSelector: async (_title: string, options: string[]) =>
				options.find(o => o.includes("Add Subscription")) ?? options[0],
			showHookInput: async () => [sampleVless1, sampleVless2].join("\n"),
		};

		await cmd.handleTui?.({ name: "vpn", args: "", text: "/vpn" } as never, { ctx: setupContext } as never);
		expect(errorMsg).toBe("");
		expect(statusMsg).toContain("Loaded 2 node");
		expect(emptyManager.upstreams.length).toBeGreaterThanOrEqual(2);

		setTunnelManagerForTest(null);
	});
});
